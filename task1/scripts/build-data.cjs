function annotate(text, dict = overrides) {
  const han = text.replace(/[^\p{Script=Han}]/gu, '');
  const readings = (dict[han] || pinyin(han, { toneType: 'symbol', type: 'array', toneSandhi: false }).join(' ')).split(' ');
  if (readings.length !== [...han].length) throw new Error(`Pinyin mismatch: ${text}`);
  let i = 0;
  return Array.from(text, char => ({char, pinyin: /\p{Script=Han}/u.test(char) ? readings[i++] : ''}));
}
const poems = fs.readFileSync(path.join(root, 'data/poems.txt'), 'utf8').split('\n').filter(l => l && !l.startsWith('#')).map((row, i) => {
  const [title, author, dynasty, original, translations, terms] = row.split('|');
  const lines = original.split('/'), meanings = translations.split('/');
  if (lines.length !== meanings.length) throw new Error(`Translation mismatch: ${title}`);
  return {id: `poem-${String(i+1).padStart(2,'0')}`, order:i+1, title, author, dynasty,
    titleTokens:annotate(title, titleOverrides), authorTokens:annotate(author, titleOverrides),
    lines:lines.map((text, n) => ({text, tokens:annotate(text), translation:meanings[n]})),
    notes:terms.split('；').map(term => {const [word, ...rest] = term.split(':'); return {word, meaning:rest.join(':')};}),
    illustration:null,
  };
});
